export const T = { en: EN, ms: MS };
export type Lang = "en" | "ms";

interface LangCtx {
  lang: Lang;
  t: (key: string) => string;
}

const LangContext = createContext<LangCtx>({
  lang: "en",
  t: (k) => (EN as Record<string, string>)[k] ?? k,
});

export function LangProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  const dict = lang === "ms" ? MS : (EN as Record<string, string>);
  const t = (k: string): string => dict[k] ?? (EN as Record<string, string>)[k] ?? k;
  return <LangContext.Provider value={{ lang, t }}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);
export const useT = (): ((k: string) => string) => useLang().t;
